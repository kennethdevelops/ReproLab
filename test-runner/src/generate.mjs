// Deterministic spec -> Playwright Test TypeScript. Every value from the spec is emitted through
// JSON.stringify, so spec text can only appear as string literals in the output.

const q = (v) => JSON.stringify(v)

function locator(loc) {
  const exactOpt = loc.exact ? ', { exact: true }' : ''
  switch (loc.kind) {
    case 'role': {
      const opts = []
      if (loc.name != null) opts.push(`name: ${q(loc.name)}`)
      if (loc.exact) opts.push('exact: true')
      return `page.getByRole(${q(loc.value)}${opts.length ? `, { ${opts.join(', ')} }` : ''})`
    }
    case 'label':
      return `page.getByLabel(${q(loc.value)}${exactOpt})`
    case 'text':
      return `page.getByText(${q(loc.value)}${exactOpt})`
    case 'test_id':
      return `page.getByTestId(${q(loc.value)})`
    case 'placeholder':
      return `page.getByPlaceholder(${q(loc.value)}${exactOpt})`
    default:
      throw new Error(`unsupported locator ${loc.kind}`)
  }
}

function describe(loc) {
  if (!loc) return 'page'
  return loc.kind === 'role' ? `${loc.value}${loc.name ? ` "${loc.name}"` : ''}` : `${loc.kind} "${loc.value}"`
}

function stepCode(s) {
  switch (s.action) {
    case 'goto':
      return [`goto ${s.path}`, `await page.goto(${q(s.path)})`]
    case 'click':
      return [`click ${describe(s.locator)}`, `await ${locator(s.locator)}.click()`]
    case 'fill':
      return [`fill ${describe(s.locator)}`, `await ${locator(s.locator)}.fill(${q(s.value)})`]
    case 'press':
      return [`press ${s.key}`, `await ${locator(s.locator)}.press(${q(s.key === 'Space' ? ' ' : s.key)})`]
    case 'select_option':
      return [`select in ${describe(s.locator)}`, `await ${locator(s.locator)}.selectOption(${q(s.value)})`]
    case 'reload':
      return ['reload', 'await page.reload()']
    case 'go_back':
      return ['go back', 'await page.goBack()']
    case 'wait_for_text':
      return [
        `wait until ${describe(s.locator)} shows ${q(s.value)}`,
        `await expect(${s.locator ? locator(s.locator) : "page.locator('body')"}).toContainText(${q(s.value)})`,
      ]
    default:
      throw new Error(`unsupported action ${s.action}`)
  }
}

function escapeRegex(text) {
  return text.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')
}

function assertCode(a) {
  const target = a.locator ? locator(a.locator) : "page.locator('body')"
  switch (a.type) {
    case 'text_visible':
      return [`${describe(a.locator)} shows ${q(a.value)}`, `await expect(${target}).toContainText(${q(a.value)})`]
    case 'text_absent':
      return [`${describe(a.locator)} does not show ${q(a.value)}`, `await expect(${target}).not.toContainText(${q(a.value)})`]
    case 'url_contains':
      return [`URL contains ${q(a.value)}`, `await expect(page).toHaveURL(new RegExp(${q(escapeRegex(a.value))}))`]
    default:
      throw new Error(`unsupported assertion ${a.type}`)
  }
}

function block(title, line) {
  return [`  await test.step(${q(title)}, async () => {`, `    ${line}`, '  })']
}

/**
 * Generate the .spec.ts source. Call only after validateSpec(spec) returned no errors.
 * Step titles start with "setup" or "assert" so a failure can be classified: a failing setup step
 * means a selector or navigation problem, a failing assert step means the intended symptom.
 */
export function generateTest(spec) {
  const lines = [
    '// Generated by ReproLab from a validated regression-test spec. Review before committing.',
    "import { expect, test } from '@playwright/test'",
    '',
    `test(${q(spec.title)}, async ({ page }) => {`,
    ...block(`setup: open ${spec.start_path}`, `await page.goto(${q(spec.start_path)})`),
  ]
  spec.steps.forEach((s, i) => lines.push(...block(`setup ${i + 1}: ${stepCode(s)[0]}`, stepCode(s)[1])))
  spec.assertions.forEach((a, i) => lines.push(...block(`assert ${i + 1}: ${assertCode(a)[0]}`, assertCode(a)[1])))
  lines.push('})', '')
  return lines.join('\n')
}
